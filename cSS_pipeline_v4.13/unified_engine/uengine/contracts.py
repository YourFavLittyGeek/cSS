"""uengine/contracts.py - Standard Component Contracts for the Percival Architecture

Pipeline:
  MRI -> ALBUS -> LUMOS + NOX -> PERCIVAL CORE -> PERCIVAL SCORE

Supporting Ecosystem:
  - PENSIEVE: Persistent Shared Core Memory & Learning History
  - SHADOW ML: Autonomous Experimental Research Laboratory
  - PERCIVAL GOVERNANCE: Proposal Evaluation, Verification & Promotion
  - PERCIVAL DATA VAULT: External Authoritative Scientific Storage
"""
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any, Tuple
import time

@dataclass
class AlbusCandidate:
    """A potential lesion candidate discovered mathematically by ALBUS."""
    cand_id: int
    study_id: str
    hemi: str                                # 'L' or 'R'
    centroid_vox: Tuple[float, float, float] # (vox_i, vox_j, vox_k)
    centroid_mm: Tuple[float, float, float]  # physical mm coordinates
    volume_vox: int
    volume_mm3: float
    bbox: Tuple[int, int, int, int, int, int] # (min_i, min_j, min_k, max_i, max_j, max_k)
    math_score: float                        # raw deterministic discovery score
    detection_version: str                   # formula / detector version string
    formula_id: str                          # active formula identifier
    quality: Dict[str, Any] = field(default_factory=dict)
    evidence: Dict[str, Any] = field(default_factory=dict) # contrast, depth, gradient
    fingerprint: str = ""                    # spatial fingerprint for persistence

@dataclass
class LumosInference:
    """3D MRI Appearance Intelligence produced by LUMOS."""
    cand_id: int
    study_id: str
    prob: Optional[float] = None             # [0.0, 1.0] image probability or None if unavailable/corrupt
    logit: Optional[float] = None            # raw model logit or None if unavailable/corrupt
    uncertainty: float = 0.0                 # test-time augmentation / dropout variance
    patch_shape: Tuple[int, ...] = ()        # 3D patch dimensions
    model_version: str = ""
    feature_vector: Optional[List[float]] = None
    has_visual_evidence: bool = True        # False if image patch was unavailable/corrupt
    depth_gradient: Optional[float] = None   # Transverse subpial depth gradient or None
    depth_gradient_status: str = "reliable" # 'reliable', 'insufficient_depth', 'unreliable_reference', 'unavailable'
    status: str = "ok"                       # 'ok', 'degraded', 'unavailable'
    error: str = ""

@dataclass
class NoxMeasurements:
    """Quantitative 3D Characteristics calculated by NOX."""
    cand_id: int
    study_id: str
    morphology: Dict[str, Any] = field(default_factory=dict)  # volume, sphericity, compactness, elongation
    topology: Dict[str, Any] = field(default_factory=dict)    # skeleton_length, branching, tortuosity
    signal: Dict[str, Any] = field(default_factory=dict)      # darkness_z, contrast, edge_gradient
    anatomy: Dict[str, Any] = field(default_factory=dict)     # pial_distance, sulcal_alignment, cortex_frac
    stability: Dict[str, str] = field(default_factory=dict)    # 'stable', 'sensitive_to_seg', 'unreliable'
    version: str = "nox-v1.0"

@dataclass
class PercivalAssessment:
    """Integrated cSS Assessment generated by PERCIVAL CORE."""
    cand_id: int
    study_id: str
    percival_score: Optional[int]            # integer [0, 100] or None if insufficient
    calibrated_prob: Optional[float]         # [0.0, 1.0] calibrated posterior
    band: str                                # 'green' (>=70), 'amber' (35-69), 'gray' (<35)
    confidence: float                        # [0.0, 1.0] assessment confidence
    uncertainty: float                       # [0.0, 1.0] epistemic + aleatoric uncertainty
    status: str                              # 'reliable', 'uncertain', 'insufficient', 'review'
    components: Dict[str, Any] = field(default_factory=dict) # ALBUS, LUMOS, NOX, Core
    absorbed_epoximise: Dict[str, Any] = field(default_factory=dict) # relationship & interaction metrics
    provenance: Dict[str, Any] = field(default_factory=dict)
    timestamp: float = field(default_factory=time.time)

@dataclass
class ShadowExperiment:
    """An autonomous hypothesis and experiment designed by SHADOW ML."""
    experiment_id: str
    hypothesis: str
    target_component: str                    # 'ALBUS', 'LUMOS', 'NOX', 'PERCIVAL_CORE', 'PIPELINE'
    baseline_version: str
    experimental_config: Dict[str, Any]
    metrics_baseline: Dict[str, float] = field(default_factory=dict)
    metrics_experimental: Dict[str, float] = field(default_factory=dict)
    status: str = "queued"                   # 'queued', 'running', 'completed', 'failed', 'proposed'
    runtime_s: float = 0.0
    error: str = ""
    reproducibility: Dict[str, Any] = field(default_factory=dict)
    data_vault_artifact_path: str = ""

@dataclass
class GovernanceProposal:
    """A proposed improvement submitted to PERCIVAL GOVERNANCE."""
    proposal_id: str
    experiment_id: str
    target_component: str
    hypothesis: str
    rationale: str
    validation_results: Dict[str, Any]
    leakage_audit_passed: bool
    sensitivity_loss: float                  # must be <= 0.0 for approval
    false_positive_reduction: float
    verdict: str = "pending"                 # 'pending', 'approved', 'rejected', 'inconclusive'
    approval_reason: str = ""
    promoted_version: str = ""
    timestamp: float = field(default_factory=time.time)
