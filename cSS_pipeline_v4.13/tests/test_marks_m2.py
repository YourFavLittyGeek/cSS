SH = (40, 40, 30)


def loop(c, r, k, n=24):
    """closed pen outline (canonical voxel coords) of radius r around c on axial slice k"""
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    return [[[float(c[0] + r * np.cos(a)), float(c[1] + r * np.sin(a)), float(k)] for a in t]]


class TestExtent(unittest.TestCase):
    def setUp(self):
        A = np.full(SH, 100.0, np.float32); self.brain = np.ones(SH, bool)
        self.les = np.zeros(SH, bool); self.les[18:22, 18:22, 8:20] = True          # a lesion 12 slices long
        self.vein = np.zeros(SH, bool); self.vein[30:33, 10:30, 14] = True            # a dark neighbour OUTSIDE the outline
        A[self.les] = 10.0; A[self.vein] = 10.0; self.A = A; self.dark = self.les | self.vein

    def test_old_region_cut_to_three_slices(self):
        mk = dict(strokes=loop((20, 20), 4, 14), shape="pen", plane="axial")
        R = PT._mark_region(mk, SH); obj, _ = PT.mark_object(self.A, self.brain, R, dark=self.dark)
        self.assertEqual(len(np.unique(np.argwhere(obj)[:, 2])), 3)                  # the documented defect

    def test_grown_to_true_extent_not_sideways(self):
        mk = dict(strokes=loop((20, 20), 4, 14), shape="pen", plane="axial")
        R, P = PT.mark_prism(mk, SH, (1.0, 1.0, 1.0)); obj, how = PT.mark_object(self.A, self.brain, R, dark=self.dark, prism_native=P)
        self.assertEqual(sorted(np.unique(np.argwhere(obj)[:, 2])), list(range(8, 20)))   # all 12 slices
        self.assertFalse((obj & self.vein).any()); self.assertTrue((obj == self.les).all()); self.assertIn("grown", how)

    def test_depth_limit_in_mm(self):
        mk = dict(strokes=loop((20, 20), 4, 14), shape="pen", plane="axial")
        _, P = PT.mark_prism(mk, SH, (1.0, 1.0, 3.0))                                 # 3 mm slices: +-12 mm = +-4 slices
        self.assertEqual(sorted(np.unique(np.argwhere(P)[:, 2])), list(range(10, 19)))

    def test_point_mark_ball(self):
        mk = dict(strokes=[[[20.0, 20.0, 14.0]]], shape="point", plane="axial")
        R, P = PT.mark_prism(mk, SH, (1.0, 1.0, 1.0)); obj, _ = PT.mark_object(self.A, self.brain, R, dark=self.dark, prism_native=P)
        self.assertGreater(len(np.unique(np.argwhere(obj)[:, 2])), 3); self.assertLessEqual(np.ptp(np.argwhere(obj)[:, 2]), 8)


class TestFate(unittest.TestCase):
    def setUp(self):
        self.b = tempfile.mkdtemp(prefix="m2_"); os.makedirs(os.path.join(self.b, "review")); os.makedirs(os.path.join(self.b, "work"))
        C = np.zeros(SH, np.int16); C[19:21, 19:21, 13:16] = 3                         # shown candidate #3, small, in the middle
        nib.save(nib.Nifti1Image(C, np.eye(4)), os.path.join(self.b, "review", "S1_candidates.nii.gz"))

    def test_enclosed_candidate_found(self):
        mk = dict(strokes=loop((20, 20), 6, 14), shape="pen", plane="axial")          # loop drawn 5 voxels away from the candidate
        R = PT._mark_region(mk, SH)
        line = np.zeros(SH, bool)
        for q in mk["strokes"][0]: line[tuple(np.round(q).astype(int))] = True
        self.assertTrue(PT.mark_fate_now(self.b, "S1", line).startswith("not generated"))     # the old judgement (line only)
        self.assertEqual(PT.mark_fate_now(self.b, "S1", R), "overlaps shown candidate #3")    # the enclosed area

    def test_reviewer_uses_the_enclosed_area(self):
        src = open(os.path.join(ROOT, "scripts", "review_web.py")).read()
        self.assertIn('elif shape == "pen" and len(pts) >= 3:', src); self.assertIn("fp = self._pen_filled(strokes, plane, pts)", src)
        self.assertIn('points=json.dumps([[[round(float(c), 1) for c in q] for q in st] for st in strokes])', src)   # strokes stored unchanged

    def test_pen_filled_geometry(self):
        import review_web as RW
        o = RW.Study.__new__(RW.Study); o.shape = SH
        st = loop((20, 20), 6, 14); pts = np.array(st[0])
        g = RW.Study._pen_filled(o, st, "axial", pts)
        self.assertTrue((g[:, 2] == 14).all()); self.assertIn([20, 20, 14], g.tolist())           # the inside, on the drawn slice
        self.assertGreater(len(g), len(pts) * 3)

    def test_consumers_use_current_fate(self):
        app = open(os.path.join(ROOT, "app", "percival_gui.py")).read(); ar = open(os.path.join(ROOT, "app", "albus_redetect.py")).read()
        self.assertIn('m.get("fate_now") or fate0.get(', app); self.assertIn("v=7", app)
        self.assertIn("PT.mark_prism(", ar); self.assertIn("prism_native=Pn", ar); self.assertIn('r.get("fate_now")', ar)


