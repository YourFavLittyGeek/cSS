#!/usr/bin/env python3
"""Regenerate ALL_CODE.md (every script, test and tool in one file). usage: python tools/make_all_code.py [VERSION]"""
import os, sys, glob
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(R)
ver = sys.argv[1] if len(sys.argv) > 1 else open("scripts/VERSION").read().strip() if os.path.exists("scripts/VERSION") else "current"
lang = {".py": "python", ".sh": "bash", ".html": "html", ".yml": "yaml", ".js": "javascript"}
out = [f"# All code - cSS pipeline {ver}\n\nGenerated by tools/make_all_code.py; the files are authoritative.\n"]
for f in sorted(glob.glob("scripts/*")) + sorted(glob.glob("tests/*")) + sorted(glob.glob("tools/*")) + ["install.sh"]:
    if not os.path.isfile(f) or f.endswith((".pyc", ".png", ".pdf", ".zip")): continue
    try: s = open(f).read()
    except Exception: continue
    out.append(f"\n## {f}\n\n````{lang.get(os.path.splitext(f)[1], '')}\n{s}\n````\n")
open("ALL_CODE.md", "w").write("".join(out)); print(f"ALL_CODE.md: {len(out) - 1} files ({ver})")
